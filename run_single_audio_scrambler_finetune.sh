#!/usr/bin/env bash

set -Eeuo pipefail

usage() {
  cat <<'EOF'
Usage:
  ./run_single_audio_scrambler_finetune.sh MODEL_NAME INPUT_AUDIO OUTPUT_DIR [OPTIONS]

Arguments:
  MODEL_NAME   audioseal, wavmark, or collaborative
  INPUT_AUDIO  One clean input audio file
  OUTPUT_DIR   Root directory for watermark, scrambler, and fine-tuned DiffWave output

Options:
  --num-scramblers N            Number of distinct scrambler targets (default: 32)
  --num-candidates N            Candidates evaluated per scrambler target (default: 1)
  --threshold VALUE             Scrambler watermark/recovery threshold (default: 0.8)
  --max-opt-iters N             Scrambler optimization iterations (default: 20)
  --max-scrambler-attempts N    Maximum scrambler generation attempts (default: 96)
  --max-steps N                 DiffWave fine-tuning steps (default: 10000)
  --preview-every N             Save a listening preview every N steps (default: 0)
  --pretrained-checkpoint PATH  Initial weights.pt (default: ./diffwave/model/weights.pt)
  --device DEVICE               Watermark and training device (default: cuda)
  --fp16                        Enable mixed-precision fine-tuning (default)
  --no-fp16                     Disable mixed-precision fine-tuning
  --fast                        Enable fast final inference (default)
  --no-fast                     Disable fast final inference
  -h, --help                    Show this help

Environment:
  PYTHON  Python executable (default: python)

Pipeline:
  clean audio -> watermark generation -> watermark validation
  -> 32 scrambler targets -> DiffWave fine-tuning -> inference -> final validation

Output:
  OUTPUT_DIR/
  ├── watermark/          Generated watermarked audio and message
  ├── watermark_validation.log
  ├── validation_results.txt
  ├── scrambler/          Generated scrambler_001.wav ... scrambler_032.wav
  ├── preprocessed/       Watermarked-audio spectrogram
  ├── model/              Fine-tuned weights, logs, and previews/
  ├── finetuned_audio/    Audio generated by the fine-tuned DiffWave
  └── finetuned_validation.log
EOF
}

if [[ $# -lt 1 ]]; then
  usage >&2
  exit 2
fi

if [[ "$1" == "-h" || "$1" == "--help" ]]; then
  usage
  exit 0
fi

if [[ $# -lt 3 ]]; then
  usage >&2
  exit 2
fi

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
MODEL_NAME="$1"
INPUT_AUDIO="$2"
OUTPUT_ROOT="$3"
shift 3

case "${MODEL_NAME}" in
  audioseal|wavmark|collaborative) ;;
  *)
    echo "Error: MODEL_NAME must be audioseal, wavmark, or collaborative; got: ${MODEL_NAME}" >&2
    exit 2
    ;;
esac

NUM_SCRAMBLERS=32
NUM_CANDIDATES=1
SCRAMBLER_THRESHOLD=0.8
SCRAMBLER_MAX_OPT_ITERS=20
SCRAMBLER_MAX_ATTEMPTS=96
MAX_STEPS=10000
PREVIEW_EVERY=0
PRETRAINED_CHECKPOINT="${SCRIPT_DIR}/diffwave/model/weights.pt"
DEVICE_NAME="cuda"
ENABLE_FP16=1
FAST_INFERENCE=1
PYTHON_BIN="${PYTHON:-python}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --num-scramblers)
      [[ $# -ge 2 ]] || { echo "Error: --num-scramblers requires a value." >&2; exit 2; }
      NUM_SCRAMBLERS="$2"
      shift 2
      ;;
    --num-candidates)
      [[ $# -ge 2 ]] || { echo "Error: --num-candidates requires a value." >&2; exit 2; }
      NUM_CANDIDATES="$2"
      shift 2
      ;;
    --threshold)
      [[ $# -ge 2 ]] || { echo "Error: --threshold requires a value." >&2; exit 2; }
      SCRAMBLER_THRESHOLD="$2"
      shift 2
      ;;
    --max-opt-iters)
      [[ $# -ge 2 ]] || { echo "Error: --max-opt-iters requires a value." >&2; exit 2; }
      SCRAMBLER_MAX_OPT_ITERS="$2"
      shift 2
      ;;
    --max-scrambler-attempts)
      [[ $# -ge 2 ]] || { echo "Error: --max-scrambler-attempts requires a value." >&2; exit 2; }
      SCRAMBLER_MAX_ATTEMPTS="$2"
      shift 2
      ;;
    --max-steps)
      [[ $# -ge 2 ]] || { echo "Error: --max-steps requires a value." >&2; exit 2; }
      MAX_STEPS="$2"
      shift 2
      ;;
    --preview-every)
      [[ $# -ge 2 ]] || { echo "Error: --preview-every requires a value." >&2; exit 2; }
      PREVIEW_EVERY="$2"
      shift 2
      ;;
    --pretrained-checkpoint)
      [[ $# -ge 2 ]] || { echo "Error: --pretrained-checkpoint requires a path." >&2; exit 2; }
      PRETRAINED_CHECKPOINT="$2"
      shift 2
      ;;
    --device)
      [[ $# -ge 2 ]] || { echo "Error: --device requires a value." >&2; exit 2; }
      DEVICE_NAME="$2"
      shift 2
      ;;
    --fp16)
      ENABLE_FP16=1
      shift
      ;;
    --no-fp16)
      ENABLE_FP16=0
      shift
      ;;
    --fast)
      FAST_INFERENCE=1
      shift
      ;;
    --no-fast)
      FAST_INFERENCE=0
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Error: unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if [[ ! -f "${INPUT_AUDIO}" ]]; then
  echo "Error: input audio does not exist: ${INPUT_AUDIO}" >&2
  exit 1
fi
if [[ -n "${PRETRAINED_CHECKPOINT}" && ! -f "${PRETRAINED_CHECKPOINT}" ]]; then
  echo "Error: pretrained checkpoint does not exist: ${PRETRAINED_CHECKPOINT}" >&2
  exit 1
fi
if ! command -v "${PYTHON_BIN}" >/dev/null 2>&1; then
  echo "Error: Python executable not found: ${PYTHON_BIN}" >&2
  exit 1
fi
if [[ "${DEVICE_NAME}" != "cuda" && "${DEVICE_NAME}" != "cpu" ]]; then
  echo "Error: --device must be cuda or cpu; got: ${DEVICE_NAME}" >&2
  exit 2
fi

for value_name in NUM_SCRAMBLERS NUM_CANDIDATES SCRAMBLER_MAX_OPT_ITERS SCRAMBLER_MAX_ATTEMPTS MAX_STEPS; do
  value="${!value_name}"
  if [[ ! "${value}" =~ ^[1-9][0-9]*$ ]]; then
    echo "Error: ${value_name} must be a positive integer; got: ${value}" >&2
    exit 2
  fi
done
if [[ ! "${SCRAMBLER_THRESHOLD}" =~ ^([0-9]+([.][0-9]*)?|[.][0-9]+)$ ]]; then
  echo "Error: --threshold must be a non-negative number; got: ${SCRAMBLER_THRESHOLD}" >&2
  exit 2
fi
if (( SCRAMBLER_MAX_ATTEMPTS < NUM_SCRAMBLERS )); then
  echo "Error: --max-scrambler-attempts must be at least --num-scramblers." >&2
  exit 2
fi
if [[ ! "${PREVIEW_EVERY}" =~ ^[0-9]+$ ]]; then
  echo "Error: --preview-every must be a non-negative integer; got: ${PREVIEW_EVERY}" >&2
  exit 2
fi

mkdir -p "${OUTPUT_ROOT}"
OUTPUT_ROOT="$(cd -- "${OUTPUT_ROOT}" && pwd)"
INPUT_AUDIO="$(readlink -f -- "${INPUT_AUDIO}")"
if [[ -n "${PRETRAINED_CHECKPOINT}" ]]; then
  PRETRAINED_CHECKPOINT="$(readlink -f -- "${PRETRAINED_CHECKPOINT}")"
fi
INPUT_BASENAME="$(basename -- "${INPUT_AUDIO}")"

WATERMARK_ROOT="${OUTPUT_ROOT}/watermark"
SCRAMBLER_DIR="${OUTPUT_ROOT}/scrambler"
PREPROCESS_DIR="${OUTPUT_ROOT}/preprocessed"
MODEL_DIR="${OUTPUT_ROOT}/model"
FINETUNED_AUDIO_DIR="${OUTPUT_ROOT}/finetuned_audio"
VALIDATION_LOG="${OUTPUT_ROOT}/watermark_validation.log"
FINETUNED_VALIDATION_LOG="${OUTPUT_ROOT}/finetuned_validation.log"
VALIDATION_RESULTS="${OUTPUT_ROOT}/validation_results.txt"
STATE_FILE="${OUTPUT_ROOT}/pipeline_input.txt"
mkdir -p \
  "${WATERMARK_ROOT}" \
  "${SCRAMBLER_DIR}" \
  "${PREPROCESS_DIR}" \
  "${MODEL_DIR}" \
  "${FINETUNED_AUDIO_DIR}"

INPUT_HASH="$(sha256sum -- "${INPUT_AUDIO}" | awk '{print $1}')"
RUN_ID="${MODEL_NAME} ${INPUT_BASENAME} ${INPUT_HASH}"
if [[ -f "${STATE_FILE}" ]]; then
  PREVIOUS_RUN_ID="$(<"${STATE_FILE}")"
  if [[ "${PREVIOUS_RUN_ID}" != "${RUN_ID}" ]]; then
    echo "Error: OUTPUT_DIR already belongs to a different input/model." >&2
    echo "Use a new OUTPUT_DIR to avoid mixing watermark and scrambler files." >&2
    exit 1
  fi
elif find "${SCRAMBLER_DIR}" -maxdepth 1 -type f -name 'scrambler_*.wav' -print -quit | grep -q .; then
  echo "Error: OUTPUT_DIR contains scrambler files but has no matching pipeline state." >&2
  echo "Use a new OUTPUT_DIR to avoid reusing scrambler files from another input." >&2
  exit 1
else
  printf '%s\n' "${RUN_ID}" > "${STATE_FILE}"
fi

TEMP_RUN_ROOT="$(mktemp -d /tmp/single_audio_scrambler_finetune.XXXXXX)"
cleanup() {
  if [[ -d "${TEMP_RUN_ROOT}" ]]; then
    rm -rf -- "${TEMP_RUN_ROOT}"
  fi
}
trap cleanup EXIT

CLEAN_INPUT_DIR="${TEMP_RUN_ROOT}/clean"
VALIDATION_AUDIO_DIR="${TEMP_RUN_ROOT}/validation"
mkdir -p "${CLEAN_INPUT_DIR}" "${VALIDATION_AUDIO_DIR}"
cp -p -- "${INPUT_AUDIO}" "${CLEAN_INPUT_DIR}/${INPUT_BASENAME}"

echo "============================================================"
echo "[1/6] Generate ${MODEL_NAME} watermarked audio"
echo "      clean input: ${INPUT_AUDIO}"
echo "      output:      ${WATERMARK_ROOT}"
"${PYTHON_BIN}" "${SCRIPT_DIR}/watermark_generation.py" \
  --model_name "${MODEL_NAME}" \
  --input_dir "${CLEAN_INPUT_DIR}" \
  --output_dir "${WATERMARK_ROOT}" \
  --device "${DEVICE_NAME}"

WATERMARK_AUDIO="${WATERMARK_ROOT}/data/${INPUT_BASENAME}"
if [[ ! -f "${WATERMARK_AUDIO}" ]]; then
  echo "Error: expected generated watermarked audio was not found: ${WATERMARK_AUDIO}" >&2
  exit 1
fi
cp -p -- "${WATERMARK_AUDIO}" "${VALIDATION_AUDIO_DIR}/${INPUT_BASENAME}"

echo "============================================================"
echo "[2/6] Validate generated watermarked audio"
"${PYTHON_BIN}" "${SCRIPT_DIR}/watermark_validation.py" \
  --model_name "${MODEL_NAME}" \
  --watermark_dir "${WATERMARK_ROOT}" \
  --audio_subdir "${VALIDATION_AUDIO_DIR}" \
  --device "${DEVICE_NAME}" 2>&1 | tee "${VALIDATION_LOG}"

awk '
  /^Average bit accuracy:/ { score = $NF; metric = "bit_accuracy" }
  /^Average detection score:/ { score = $NF; metric = "detection_score" }
  /^ASR:/ { asr = $NF }
  END {
    if (score == "") score = "N/A"
    if (metric == "") metric = "score"
    if (asr == "") asr = "N/A"
    printf "Watermarked: %s=%s, ASR=%s\n", metric, score, asr
  }
' "${VALIDATION_LOG}" > "${VALIDATION_RESULTS}"

echo "============================================================"
echo "[3/6] Generate ${NUM_SCRAMBLERS} distinct scrambler targets"
echo "      input:  ${WATERMARK_AUDIO}"
echo "      output: ${SCRAMBLER_DIR}"
"${PYTHON_BIN}" "${SCRIPT_DIR}/generate_scrambler.py" \
  --input_audio "${WATERMARK_AUDIO}" \
  --output_dir "${SCRAMBLER_DIR}" \
  --num_scramblers "${NUM_SCRAMBLERS}" \
  --num_candidates "${NUM_CANDIDATES}" \
  --threshold "${SCRAMBLER_THRESHOLD}" \
  --max_opt_iters "${SCRAMBLER_MAX_OPT_ITERS}" \
  --max_attempts "${SCRAMBLER_MAX_ATTEMPTS}"

mapfile -d '' SCRAMBLER_FILES < <(
  find "${SCRAMBLER_DIR}" -maxdepth 1 -type f -name 'scrambler_*.wav' -print0 | sort -z
)
if [[ ${#SCRAMBLER_FILES[@]} -lt ${NUM_SCRAMBLERS} ]]; then
  echo "Error: expected ${NUM_SCRAMBLERS} scrambler files, found ${#SCRAMBLER_FILES[@]}." >&2
  exit 1
fi
SCRAMBLER_FILES=("${SCRAMBLER_FILES[@]:0:${NUM_SCRAMBLERS}}")

echo "============================================================"
echo "[4/6] Fine-tune DiffWave with one watermarked source and ${#SCRAMBLER_FILES[@]} scrambler targets"
echo "      source: ${WATERMARK_AUDIO}"
if [[ -n "${PRETRAINED_CHECKPOINT}" ]]; then
  echo "      initial model: ${PRETRAINED_CHECKPOINT}"
else
  echo "      initial model: random initialization (train from scratch)"
fi
echo "      output: ${MODEL_DIR}"

FINETUNE_ARGS=(
  --input_audio "${WATERMARK_AUDIO}"
  --scrambler_files "${SCRAMBLER_FILES[@]}"
  --output_dir "${MODEL_DIR}"
  --preprocess_dir "${PREPROCESS_DIR}"
  --max_steps "${MAX_STEPS}"
  --preview_every "${PREVIEW_EVERY}"
  --device "${DEVICE_NAME}"
)
if [[ -n "${PRETRAINED_CHECKPOINT}" ]]; then
  FINETUNE_ARGS+=(--pretrained_checkpoint "${PRETRAINED_CHECKPOINT}")
fi
if [[ ${ENABLE_FP16} -eq 1 ]]; then
  FINETUNE_ARGS+=(--fp16)
fi
if [[ ${FAST_INFERENCE} -eq 1 ]]; then
  FINETUNE_ARGS+=(--preview_fast)
fi

"${PYTHON_BIN}" "${SCRIPT_DIR}/finetune_diffwave_scrambler.py" "${FINETUNE_ARGS[@]}"

echo "============================================================"
echo "[5/6] Run inference with the fine-tuned DiffWave"
echo "      input:  ${PREPROCESS_DIR}"
echo "      model:  ${MODEL_DIR}"
echo "      output: ${FINETUNED_AUDIO_DIR}"

INFERENCE_ARGS=(
  --model_dir "${MODEL_DIR}"
  --input_dir "${PREPROCESS_DIR}"
  --output_dir "${FINETUNED_AUDIO_DIR}"
  --device "${DEVICE_NAME}"
  --num_samples 1
)
if [[ ${FAST_INFERENCE} -eq 1 ]]; then
  INFERENCE_ARGS+=(--fast)
fi
"${PYTHON_BIN}" "${SCRIPT_DIR}/inference.py" "${INFERENCE_ARGS[@]}"

FINETUNED_AUDIO="${FINETUNED_AUDIO_DIR}/${INPUT_BASENAME}"
if [[ ! -f "${FINETUNED_AUDIO}" ]]; then
  echo "Error: fine-tuned inference audio was not found: ${FINETUNED_AUDIO}" >&2
  exit 1
fi

echo "============================================================"
echo "[6/6] Validate target watermark in fine-tuned inference audio"
"${PYTHON_BIN}" "${SCRIPT_DIR}/watermark_validation.py" \
  --model_name "${MODEL_NAME}" \
  --watermark_dir "${WATERMARK_ROOT}" \
  --audio_subdir "${FINETUNED_AUDIO_DIR}" \
  --device "${DEVICE_NAME}" 2>&1 | tee "${FINETUNED_VALIDATION_LOG}"

awk '
  /^Average bit accuracy:/ { score = $NF; metric = "bit_accuracy" }
  /^Average detection score:/ { score = $NF; metric = "detection_score" }
  /^ASR:/ { asr = $NF }
  END {
    if (score == "") score = "N/A"
    if (metric == "") metric = "score"
    if (asr == "") asr = "N/A"
    printf "FineTuned: %s=%s, ASR=%s\n", metric, score, asr
  }
' "${FINETUNED_VALIDATION_LOG}" >> "${VALIDATION_RESULTS}"

echo "============================================================"
echo "Done."
echo "Watermarked audio:  ${WATERMARK_AUDIO}"
echo "Scrambler targets:    ${SCRAMBLER_DIR}"
echo "Fine-tuned model:   ${MODEL_DIR}/weights.pt"
echo "Fine-tuned audio:   ${FINETUNED_AUDIO}"
echo "Validation results: ${VALIDATION_RESULTS}"
cat "${VALIDATION_RESULTS}"
